def _root():
    return Path(os.environ.get("AFK_ROOT", Path(__file__).resolve().parents[1]))


def _read(path):
    with open(path, "r", encoding="utf-8", newline="") as f:
        return f.read()


def _write(path, text):
    """原子替换写盘。

    历史缺陷：这里原来是 `open(path, "w")` —— 先把目标文件截断到 0 再逐块写。
    更新流程（afk_core/updater.py 先 cmd_revert、pull 完再 cmd_apply）与手工
    的 apply/verify 可以同时在跑，另一路在这个窗口里 _read 就会读到半截文件；
    再基于半截内容 apply 并写回，落盘结果是「打好补丁的前半段 + 残留的旧
    尾部」。实测 BAAH/main.py 就是这样长出一段 `re_process` 垃圾、变成
    IndentationError，项目再也起不来（logs/reports/20261106_075601_BAAH）。

    改为同目录临时文件 + os.replace：要么是完整旧文件，要么是完整新文件，
    读的一方永远看不到中间态。
    """
    path = Path(path)
    tmp = path.with_name(path.name + ".afk-tmp")
    try:
        with open(tmp, "w", encoding="utf-8", newline="") as f:
            f.write(text)
        os.replace(tmp, path)
    finally:
        if tmp.exists():
            try:
                tmp.unlink()
            except OSError:
                pass


def _prefix_for(file_name):
    return "//" if Path(file_name).suffix.lower() in SLASH_SUFFIXES else "#"


def _markers(block):
    prefix = _prefix_for(block["file"])
    return BEGIN.format(prefix, block["id"]), END.format(prefix, block["id"])


def _dominant_newline(text):
    """目标文件的主体行尾。

    为什么需要：补丁块原来一律用 "\\n" 拼。插进 CRLF 的 Windows 源码后，
    文件变成混合行尾，`git diff` 里整块都是 LF 噪声，也容易被编辑器的
    「统一行尾」二次改写。这里跟随文件本身的风格。
    """
    crlf = text.count("\r\n")
    lf = text.count("\n") - crlf
    return "\r\n" if crlf > lf else "\n"


def _block_text(block, newline="\n"):
    begin, end = _markers(block)
    return begin + newline + block["insert"].replace("\n", newline) + end + newline


def _find_block(text, block):
    candidates = []
    prefix = _prefix_for(block["file"])
    other = "#" if prefix == "//" else "//"
    for p in (prefix, other):
        candidates.append((BEGIN.format(p, block["id"]), END.format(p, block["id"])))
    for begin, end in candidates:
        start = text.find(begin)
        if start < 0:
            continue
        stop = text.find(end, start)
        if stop < 0:
            continue
        stop += len(end)
        # 吃掉标记行自身的行尾：CRLF 是 2 个字符，LF 是 1 个
        if text.startswith("\r\n", stop):
            stop += 2
        elif text.startswith("\n", stop):
            stop += 1
        return start, stop
    return None


def apply_block(text, block):
    newline = _dominant_newline(text)
    expected = _block_text(block, newline)
    found = _find_block(text, block)
    if found:
        start, stop = found
        current = text[start:stop]
        if current == expected:
            return text, "unchanged"
        return text[:start] + expected + text[stop:], "updated"
    anchor = block["anchor"]
    idx = text.find(anchor)
    if idx < 0:
        raise RuntimeError("anchor not found for block {0}: {1!r}".format(block["id"], anchor))
    line_end = text.find("\n", idx)
    if line_end < 0:
        line_end = len(text)
    else:
        line_end += 1
    return text[:line_end] + expected + text[line_end:], "applied"


def revert_block(text, block):
    found = _find_block(text, block)
    if not found:
        return text, "absent"
    start, stop = found
    return text[:start] + text[stop:], "reverted"


def verify_block(text, block):
    expected = _block_text(block, _dominant_newline(text))
    found = _find_block(text, block)
    if found:
        current = text[found[0]:found[1]]
        return "ok" if current == expected else "drifted"
    if block["anchor"] in text:
        return "missing"
    return "anchor-missing"


def _manifest_path(project_dir):
    return project_dir / ".afk_monitor_manifest.json"


def _load_manifest(project_dir):
    path = _manifest_path(project_dir)
    if path.exists():
        try:
            return json.loads(path.read_text(encoding="utf-8"))
        except Exception:
            return {}
    return {}


def _save_manifest(project_dir, data):
    _manifest_path(project_dir).write_text(json.dumps(data, indent=2, ensure_ascii=False), encoding="utf-8")


def _sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


def _apply_drops(project_dir, spec, kit_dir, dry_run, results):
    manifest = _load_manifest(project_dir)
    manifest.setdefault("drops", {})
    for drop in spec.get("drops", []):
        src = kit_dir / "patches" / drop["src"]
        dst = project_dir / drop["dst"]
        digest = _sha256(src)
        if dst.exists() and manifest["drops"].get(drop["dst"]) == digest:
            results.append((drop["dst"], "unchanged"))
            continue
        if dry_run:
            results.append((drop["dst"], "would-drop"))
            continue
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(src, dst)
        manifest["drops"][drop["dst"]] = digest
        results.append((drop["dst"], "dropped"))
    if not dry_run:
        _save_manifest(project_dir, manifest)


def _revert_drops(project_dir, spec, results):
    manifest = _load_manifest(project_dir)
    for drop in spec.get("drops", []):
        dst = project_dir / drop["dst"]
        if dst.exists() and manifest.get("drops", {}).get(drop["dst"]):
            if not dst.read_text(encoding="utf-8", errors="ignore").startswith("package main"):
                results.append((drop["dst"], "skip-foreign"))
                continue
            dst.unlink()
            results.append((drop["dst"], "removed"))
    manifest["drops"] = {}
    _save_manifest(project_dir, manifest)


def _targets(root, only=None):
    for name, spec in PATCHES.items():
        if only and name not in only:
            continue
        yield name, spec, root / spec["path"]


def _syntax_error(path, text):
    """打补丁后先编译一遍，语法不通过就不要落盘。

    历史缺陷：补丁把 `sys.exit(1)` 插在 `input("Error, Enter to exit/...")`
    之后，只要插入点算错一位（行尾是 CRLF 还是 LF、标记有没有吃掉换行），
    写出去的文件就是 IndentationError —— 而 apply 仍然报 "applied"，于是
    更新流程愉快地留下一个起不来的项目，直到用户点「启动」才炸
    （logs/reports/20261106_075601_BAAH，BAAH/main.py line 52）。
    这里在写盘之前编译一次，出问题就保留原文件并把错误报出去。
    """
    if Path(path).suffix.lower() != ".py":
        return None
    try:
        compile(text, str(path), "exec")
    except SyntaxError as exc:
        return "{0}: {1} (line {2})".format(type(exc).__name__, exc.msg, exc.lineno)
    except ValueError as exc:
        return str(exc)
    return None


def cmd_apply(root, only=None, dry_run=False):
    kit_dir = Path(__file__).resolve().parent
    report = {}
    for name, spec, project_dir in _targets(root, only):
        results = []
        if not project_dir.exists():
            report[name] = [("project", "missing")]
            continue
        for block in spec.get("blocks", []):
            path = project_dir / block["file"]
            if not path.exists():
                results.append((block["file"], "file-missing"))
                continue
            if dry_run:
                state = verify_block(_read(path), block)
                results.append((block["file"] + ":" + block["id"], "would-" + ("skip" if state == "ok" else "apply")))
                continue
            try:
                text = _read(path)
                new_text, state = apply_block(text, block)
                if new_text != text:
                    broken = _syntax_error(path, new_text)
                    if broken:
                        results.append((block["file"] + ":" + block["id"],
                                        "error: 语法检查失败，未写入 ({0})".format(broken)))
                        continue
                    _write(path, new_text)
                results.append((block["file"] + ":" + block["id"], state))
            except Exception as exc:
                results.append((block["file"] + ":" + block["id"], "error: " + str(exc)))
        _apply_drops(project_dir, spec, kit_dir, dry_run, results)
        report[name] = results
    return report

def cmd_revert(root, only=None):
    report = {}
    for name, spec, project_dir in _targets(root, only):
        results = []
        if not project_dir.exists():
            report[name] = [("project", "missing")]
            continue
        for block in spec.get("blocks", []):
            path = project_dir / block["file"]
            if not path.exists():
                continue
            text = _read(path)
            new_text, state = revert_block(text, block)
            if state == "reverted":
                _write(path, new_text)
            results.append((block["file"] + ":" + block["id"], state))
        _revert_drops(project_dir, spec, results)
        report[name] = results
    return report


def cmd_verify(root, only=None):
    kit_dir = Path(__file__).resolve().parent
    report = {}
    for name, spec, project_dir in _targets(root, only):
        results = []
        if not project_dir.exists():
            report[name] = [("project", "missing")]
            continue
        for block in spec.get("blocks", []):
            path = project_dir / block["file"]
            if not path.exists():
                results.append((block["file"], "file-missing"))
                continue
            text = _read(path)
            state = verify_block(text, block)
            # 关键：补丁块「在位」不等于文件能用。2026-11-06 那次事故里
            # BAAH/main.py 的三个补丁块都还在、verify 全 ok，文件却是
            # IndentationError —— 光看标记发现不了，得编译一次。
            if state == "ok":
                broken = _syntax_error(path, text)
                if broken:
                    state = "syntax-broken"
                    results.append((block["file"] + ":" + block["id"] + " (" + broken + ")", state))
                    continue
            results.append((block["file"] + ":" + block["id"], state))
        manifest = _load_manifest(project_dir)
        for drop in spec.get("drops", []):
            dst = project_dir / drop["dst"]
            src = kit_dir / "patches" / drop["src"]
            if not dst.exists():
                results.append((drop["dst"], "drop-missing"))
            elif manifest.get("drops", {}).get(drop["dst"]) == _sha256(src):
                results.append((drop["dst"], "ok"))
            else:
                results.append((drop["dst"], "drop-drifted"))
        report[name] = results
    return report


def main(argv=None):
    parser = argparse.ArgumentParser(description="Auto-AFK monitor patch manager")
    parser.add_argument("command", choices=["apply", "revert", "verify"])
    parser.add_argument("--project", action="append", dest="projects")
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument("--json", action="store_true")
    args = parser.parse_args(argv)
    root = _root()
    if args.command == "apply":
        report = cmd_apply(root, args.projects, args.dry_run)
    elif args.command == "revert":
        report = cmd_revert(root, args.projects)
    else:
        report = cmd_verify(root, args.projects)
    if args.json:
        print(json.dumps(report, ensure_ascii=False, indent=2))
    else:
        for project, results in report.items():
            print("[{0}]".format(project))
            for item, state in results:
                print("  {0:<55} {1}".format(item, state))
    failed = any(
        state.startswith("error") or state in (
            "anchor-missing", "file-missing", "drifted", "missing",
            "drop-missing", "drop-drifted", "syntax-broken",
        )
        for results in report.values()
        for _, state in results
    )
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
